const dictionaries: Record<Exclude<Language, Language.Auto>, Record<MessageKey, string>> = { en, ru };

let current: Exclude<Language, Language.Auto> = Language.English;

function obsidianLanguage(): string {
	// getLanguage() arrived in Obsidian 1.8.7; before it, the app set
	// moment's locale to its own language. The check is by version rather
	// than typeof so the plugin review's API check can see the guard.
	return requireApiVersion("1.8.7") ? getLanguage() : moment.locale();
}

export function setLanguage(language: Language): void {
	const code = language === Language.Auto ? obsidianLanguage() : language;
	current = code.toLowerCase().startsWith("ru") ? Language.Russian : Language.English;
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
	let text = dictionaries[current][key];
	if (vars) {
		for (const [name, value] of Object.entries(vars)) {
			text = text.replace(`{${name}}`, String(value));
		}
	}
	return text;
}
